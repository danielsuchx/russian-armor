//! Tauri commands for OS autostart and background AI service guard (`CoworkVMService` / macOS).

use crate::{autostart, cowork_guard, state};

#[tauri::command]
pub async fn get_autostart_status(
    state: tauri::State<'_, state::AppState>,
) -> Result<autostart::AutostartStatus, String> {
    let saved = state.is_autostart_enabled().await;
    tokio::task::spawn_blocking(move || autostart::get_status(saved))
        .await
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub async fn set_autostart_enabled(
    enabled: bool,
    state: tauri::State<'_, state::AppState>,
) -> Result<autostart::AutostartStatus, String> {
    let active_in_os = tokio::task::spawn_blocking(move || autostart::apply_os_autostart(enabled))
        .await
        .map_err(|e| e.to_string())??;
    state
        .set_autostart_enabled(enabled)
        .await
        .map_err(|e| e.to_string())?;
    Ok(autostart::build_status(enabled, active_in_os))
}

#[tauri::command]
pub async fn get_cowork_guard_status() -> Result<cowork_guard::CoworkGuardStatus, String> {
    tokio::task::spawn_blocking(cowork_guard::get_cowork_guard_status)
        .await
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub async fn install_or_repair_cowork_guard(
    state: tauri::State<'_, state::AppState>,
) -> Result<cowork_guard::CoworkGuardStatus, String> {
    let status = tokio::task::spawn_blocking(cowork_guard::install_or_repair_cowork_guard)
        .await
        .map_err(|e| e.to_string())??;
    let enabled = status.task_installed && status.task_healthy;
    let _ = state.set_cowork_guard_enabled(enabled).await;
    Ok(status)
}

// Native Russian Armor IPC adapter. Generated by scripts/generate-engine-bridge.py.
pub(crate) async fn native_call(native_command: &str, native_args: serde_json::Value, native_app: tauri::AppHandle) -> Result<serde_json::Value, serde_json::Value> {
    use tauri::Manager as _;
    let _ = (&native_args, &native_app);
    match native_command {
        "get_autostart_status" => crate::native_bridge::result(get_autostart_status(native_app.state::<state::AppState>()).await),
        "set_autostart_enabled" => crate::native_bridge::result(set_autostart_enabled(crate::native_bridge::argument(&native_args, "enabled")?, native_app.state::<state::AppState>()).await),
        "get_cowork_guard_status" => crate::native_bridge::result(get_cowork_guard_status().await),
        "install_or_repair_cowork_guard" => crate::native_bridge::result(install_or_repair_cowork_guard(native_app.state::<state::AppState>()).await),
        _ => Err(serde_json::json!({"message":"Unknown command"})),
    }
}
