//! Custom AI domain list commands.

use crate::state;

#[tauri::command]
pub async fn get_custom_ai_domains_cmd(
    state: tauri::State<'_, state::AppState>,
) -> Result<Vec<String>, String> {
    Ok(state.get_custom_ai_domains().await)
}

#[tauri::command]
pub async fn add_custom_ai_domain_cmd(
    domain: String,
    state: tauri::State<'_, state::AppState>,
) -> Result<Vec<String>, String> {
    state
        .add_custom_ai_domain(domain)
        .await
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub async fn remove_custom_ai_domain_cmd(
    domain: String,
    state: tauri::State<'_, state::AppState>,
) -> Result<Vec<String>, String> {
    state
        .remove_custom_ai_domain(&domain)
        .await
        .map_err(|e| e.to_string())
}

// Native Russian Armor IPC adapter. Generated by scripts/generate-engine-bridge.py.
pub(crate) async fn native_call(native_command: &str, native_args: serde_json::Value, native_app: tauri::AppHandle) -> Result<serde_json::Value, serde_json::Value> {
    use tauri::Manager as _;
    let _ = (&native_args, &native_app);
    match native_command {
        "get_custom_ai_domains_cmd" => crate::native_bridge::result(get_custom_ai_domains_cmd(native_app.state::<state::AppState>()).await),
        "add_custom_ai_domain_cmd" => crate::native_bridge::result(add_custom_ai_domain_cmd(crate::native_bridge::argument(&native_args, "domain")?, native_app.state::<state::AppState>()).await),
        "remove_custom_ai_domain_cmd" => crate::native_bridge::result(remove_custom_ai_domain_cmd(crate::native_bridge::argument(&native_args, "domain")?, native_app.state::<state::AppState>()).await),
        _ => Err(serde_json::json!({"message":"Unknown command"})),
    }
}
