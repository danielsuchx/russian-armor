//! Payment BIN checker and account warm-up timer commands.

use super::AppContext;
use crate::bin_checker;

#[tauri::command]
pub async fn check_payment_bin(
    bin: String,
    vpn_country: Option<String>,
    checker: tauri::State<'_, bin_checker::BinChecker>,
) -> Result<bin_checker::BinAuditResult, String> {
    checker.check_bin(&bin, vpn_country.as_deref()).await
}

#[tauri::command]
pub async fn set_warmup_timer(
    timestamp: Option<u64>,
    state: tauri::State<'_, AppContext>,
) -> Result<Option<u64>, String> {
    state
        .set_warmup_started_at(timestamp)
        .await
        .map_err(|e| e.to_string())?;
    Ok(timestamp)
}

// Native Russian Armor IPC adapter. Generated by scripts/generate-engine-bridge.py.
pub(crate) async fn native_call(native_command: &str, native_args: serde_json::Value, native_app: tauri::AppHandle) -> Result<serde_json::Value, serde_json::Value> {
    use tauri::Manager as _;
    let _ = (&native_args, &native_app);
    match native_command {
        "check_payment_bin" => crate::native_bridge::result(check_payment_bin(crate::native_bridge::argument(&native_args, "bin")?, crate::native_bridge::argument(&native_args, "vpnCountry")?, native_app.state::<bin_checker::BinChecker>()).await),
        "set_warmup_timer" => crate::native_bridge::result(set_warmup_timer(crate::native_bridge::argument(&native_args, "timestamp")?, native_app.state::<AppContext>()).await),
        _ => Err(serde_json::json!({"message":"Unknown command"})),
    }
}
