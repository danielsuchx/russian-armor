//! Application update commands.

use crate::{state, updater};

#[tauri::command]
pub async fn check_for_updates(
    app: tauri::AppHandle,
) -> Result<updater::UpdateCheckResult, updater::UpdateFailure> {
    updater::check_for_updates(&app).await
}

/// Installs the update announced by the pinned, signed endpoint. Takes nothing from the frontend.
#[tauri::command]
pub async fn install_update(
    app: tauri::AppHandle,
) -> Result<updater::InstallUpdateResult, updater::UpdateFailure> {
    updater::install_update(&app).await
}

/// Lists signed GitHub releases strictly older than the running version that have a `latest.json` manifest.
#[tauri::command]
pub async fn list_rollback_versions()
-> Result<Vec<updater::RollbackReleaseInfo>, updater::UpdateFailure> {
    updater::list_rollback_versions().await
}

/// Downloads, verifies (minisign), and installs a signed older release for rollback.
#[tauri::command]
pub async fn install_rollback_version(
    app: tauri::AppHandle,
    version: String,
) -> Result<updater::InstallUpdateResult, updater::UpdateFailure> {
    updater::install_rollback_version(&app, &version).await
}

#[tauri::command]
pub async fn toggle_auto_update(
    enabled: bool,
    state: tauri::State<'_, state::AppState>,
) -> Result<(), String> {
    state
        .set_auto_update_enabled(enabled)
        .await
        .map_err(|e| e.to_string())
}

// Native Russian Armor IPC adapter. Generated by scripts/generate-engine-bridge.py.
pub(crate) async fn native_call(native_command: &str, native_args: serde_json::Value, native_app: tauri::AppHandle) -> Result<serde_json::Value, serde_json::Value> {
    use tauri::Manager as _;
    let _ = (&native_args, &native_app);
    match native_command {
        "check_for_updates" => crate::native_bridge::result(check_for_updates(native_app.clone()).await),
        "install_update" => crate::native_bridge::result(install_update(native_app.clone()).await),
        "list_rollback_versions" => crate::native_bridge::result(list_rollback_versions().await),
        "install_rollback_version" => crate::native_bridge::result(install_rollback_version(native_app.clone(), crate::native_bridge::argument(&native_args, "version")?).await),
        "toggle_auto_update" => crate::native_bridge::result(toggle_auto_update(crate::native_bridge::argument(&native_args, "enabled")?, native_app.state::<state::AppState>()).await),
        _ => Err(serde_json::json!({"message":"Unknown command"})),
    }
}
