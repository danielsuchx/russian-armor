"""Generate typed native IPC adapters from the vendored command signatures.

The fixed dispatch list is the same Rust implementation used by upstream IPC.
No source strings are evaluated and no arbitrary functions can be requested.
"""
from pathlib import Path
import json
import re

root = Path(__file__).resolve().parents[1] / "NetworkEngine"
rust = root / "src-tauri/src"
bootstrap = (rust / "app/mod.rs").read_text()
start = bootstrap.index(".invoke_handler(")
end = bootstrap.index(".build(tauri::generate_context!())", start)
registered = re.findall(r"commands::([a-z_]+)::([a-z_0-9]+)", bootstrap[start:end])
wanted = {name for _, name in registered}
excluded = {"check_for_updates", "install_update", "list_rollback_versions",
            "install_rollback_version", "toggle_auto_update", "get_autostart_status",
            "set_autostart_enabled", "copy_text_to_clipboard"}
marker = "\n// Native Russian Armor IPC adapter."
covered = []
groups = {}
for path in (rust / "commands").rglob("*.rs"):
    text = path.read_text().split(marker)[0]
    arms = []
    for match in re.finditer(r"pub (async )?fn (\w+)\(", text):
        name = match[2]
        if name not in wanted:
            continue
        depth, index = 1, match.end()
        while depth:
            if text[index] == "(": depth += 1
            if text[index] == ")": depth -= 1
            index += 1
        parameters = text[match.end():index-1].strip().rstrip(",")
        result_type = text[index:text.find("{", index)].strip()
        arguments = []
        for parameter in re.split(r",\s*(?=[a-z_]+\s*:(?!:))", parameters) if parameters else []:
            parameter_name, parameter_type = parameter.strip().split(":", 1)
            parameter_type = parameter_type.strip()
            if parameter_type == "tauri::AppHandle":
                arguments.append("native_app.clone()")
            elif parameter_type.startswith("tauri::State<"):
                state_type = re.match(r"tauri::State<'_,\s*(.*)>$", parameter_type)[1]
                arguments.append("native_app.state::<" + state_type + ">()")
            else:
                key = re.sub(r"_([a-z])", lambda m: m[1].upper(), parameter_name)
                arguments.append(f'crate::native_bridge::argument(&native_args, "{key}")?')
        call = name + "(" + ", ".join(arguments) + ")" + (".await" if match[1] else "")
        conversion = "result" if result_type.startswith("-> Result<") else "value"
        arms.append(f'"{name}" => crate::native_bridge::{conversion}({call}),')
        covered.append(name)
    if arms:
        module = str(path.relative_to(rust / "commands")).split("/")[0].replace(".rs", "")
        groups[module] = [name for group, name in registered if group == module]
        text += marker + " Generated by scripts/generate-engine-bridge.py.\n"
        text += 'pub(crate) async fn native_call(native_command: &str, native_args: serde_json::Value, native_app: tauri::AppHandle) -> Result<serde_json::Value, serde_json::Value> {\n'
        text += '    use tauri::Manager as _;\n    let _ = (&native_args, &native_app);\n    match native_command {\n        '
        text += "\n        ".join(arms)
        text += '\n        _ => Err(serde_json::json!({"message":"Unknown command"})),\n    }\n}\n'
        if path.read_text() != text:
            path.write_text(text)
assert sorted(covered) == sorted(wanted), (len(covered), len(wanted))
lines = ['// Fixed native IPC dispatch; generated from registered commands.',
         'use serde_json::Value;',
         'pub async fn dispatch(app: tauri::AppHandle, command: &str, args: Value) -> Result<Value, Value> {',
         '    match command {']
for module, names in groups.items():
    names = [name for name in names if name not in excluded]
    if names:
        patterns = ' | '.join('"' + name + '"' for name in names)
        lines.append(f'        {patterns} => crate::commands::{module}::native_call(command, args, app).await,')
lines += ['        _ => Err(serde_json::json!({"message":"Command is owned by the native application or unavailable"})),', '    }', '}']
outputs = {rust / "native_dispatch.rs": "\n".join(lines) + "\n",
           root / "native-commands.json": json.dumps({"engine": [name for _, name in registered if name not in excluded], "native": sorted(excluded)}, indent=2) + "\n"}
for path, content in outputs.items():
    if not path.exists() or path.read_text() != content:
        path.write_text(content)
print(f"Generated {len(covered)} typed adapters ({len(excluded)} parent-owned commands)")
